# 通过关键字def定义求阶乘的函数
# 自变量（参数）num是一个非负整数
# 因变量（返回值）是num的阶乘
def fac(num):
    result = 1
    for n in range(2, num + 1):
        result *= n
    return result

m = int(input('m = '))
n = int(input('n = '))

# 计算C(M,N)的值
print(fac(m) // fac(n) // fac(m - n))
#使用整除是因为组合数结果一定是整数,阶乘很大时，转成浮点数还可能损失精度。